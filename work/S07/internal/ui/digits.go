package ui

var digits = map[rune][5]string{
	'0': {"1111", "1001", "1001", "1001", "1111"},
	'1': {"0010", "0110", "0010", "0010", "0111"},
	'2': {"1111", "0001", "1111", "1000", "1111"},
	'3': {"1111", "0001", "0111", "0001", "1111"},
	'4': {"1001", "1001", "1111", "0001", "0001"},
	'5': {"1111", "1000", "1111", "0001", "1111"},
	'6': {"1111", "1000", "1111", "1001", "1111"},
	'7': {"1111", "0001", "0010", "0100", "0100"},
	'8': {"1111", "1001", "1111", "1001", "1111"},
	'9': {"1111", "1001", "1111", "0001", "1111"},
	':': {"00", "11", "00", "11", "00"},
	'.': {"0", "0", "0", "0", "1"},
	'-': {"0000", "0000", "1111", "0000", "0000"},
}

func (c *Canvas) Digits(x, y int, text string, color Color, scale int) int {
	start := x
	for _, r := range text {
		glyph, ok := digits[r]
		if !ok {
			continue
		}
		for row, line := range glyph {
			for col, bit := range line {
				if bit == '1' {
					for s := 0; s < scale; s++ {
						c.Put(x+col*scale+s, y+row, '█', color, Background)
					}
				}
			}
		}
		x += (len(glyph[0]) + 1) * scale
	}
	return x - start
}
